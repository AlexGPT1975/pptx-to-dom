// Turns data/presetShapeDefinitions.xml (ECMA-376 Part 1, see NOTICE.md) into
// src/presets.generated.ts: per preset its adjust defaults, guides, text rectangle and paths,
// as plain data. Run by `npm run build`; the XML itself is not shipped.
import { readFileSync, writeFileSync } from "node:fs";
import { DOMParser } from "@xmldom/xmldom";

const xml = readFileSync(new URL("../data/presetShapeDefinitions.xml", import.meta.url), "utf8");
const doc = new DOMParser().parseFromString(xml, "text/xml");
const els = (n) => Array.from(n.childNodes).filter((c) => c.nodeType === 1);
const out = {};
for (const shape of els(doc.documentElement)) {
  const def = { av: [], gd: [], rect: null, paths: [] };
  for (const part of els(shape)) {
    const t = part.localName;
    if (t === "avLst" || t === "gdLst") {
      for (const gd of els(part)) (t === "avLst" ? def.av : def.gd).push([gd.getAttribute("name"), gd.getAttribute("fmla")]);
    } else if (t === "rect") {
      def.rect = ["l", "t", "r", "b"].map((k) => part.getAttribute(k));
    } else if (t === "pathLst") {
      for (const p of els(part)) {
        const path = { w: p.getAttribute("w") || "", h: p.getAttribute("h") || "",
                       fill: p.getAttribute("fill") || "norm", stroke: p.getAttribute("stroke") || "true", c: [] };
        for (const cmd of els(p)) {
          const k = cmd.localName;
          const pts = els(cmd).filter((e) => e.localName === "pt").map((e) => [e.getAttribute("x"), e.getAttribute("y")]);
          if (k === "arcTo") path.c.push(["A", cmd.getAttribute("wR"), cmd.getAttribute("hR"), cmd.getAttribute("stAng"), cmd.getAttribute("swAng")]);
          else if (k === "close") path.c.push(["Z"]);
          else path.c.push([{ moveTo: "M", lnTo: "L", cubicBezTo: "C", quadBezTo: "Q" }[k], ...pts.flat()]);
        }
        def.paths.push(path);
      }
    }
  }
  out[shape.localName] = def;
}
const header = "// GENERATED by scripts/build-presets.mjs from ECMA-376 presetShapeDefinitions.xml - do not edit.\n" +
  "// Copyright Ecma International; see NOTICE.md.\n";
writeFileSync(new URL("../src/presets.generated.ts", import.meta.url),
  header + "export const PRESETS: Record<string, PresetDef> = " + JSON.stringify(out) + ";\n" +
  "export interface PresetPath { w: string; h: string; fill: string; stroke: string; c: string[][] }\n" +
  "export interface PresetDef { av: [string, string][]; gd: [string, string][]; rect: string[] | null; paths: PresetPath[] }\n");
console.log(`presets: ${Object.keys(out).length}`);
